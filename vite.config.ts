import { defineConfig, type Plugin } from 'vite';
import { fileURLToPath } from 'node:url';

const phaserProductionBuild = fileURLToPath(new URL('./node_modules/phaser/dist/phaser.esm.min.js', import.meta.url));
const bundleCompositionReport: Plugin = {
  name: 'bird-squad-bundle-composition-report',
  generateBundle(_options, bundle) {
    if (process.env.BIRD_SQUAD_BUNDLE_REPORT !== '1') return;
    Object.values(bundle)
      .filter((entry) => entry.type === 'chunk' && (entry.isEntry || entry.name === 'index'))
      .forEach((entry) => {
        const modules = Object.entries(entry.modules)
          .map(([id, detail]) => ({
            id: id.replace(/\\/g, '/').replace(`${process.cwd().replace(/\\/g, '/')}/`, ''),
            bytes: detail.renderedLength,
          }))
          .sort((a, b) => b.bytes - a.bytes);
        console.log(`\nBundle composition: ${entry.fileName} (${entry.code.length} generated bytes)`);
        modules.slice(0, 40).forEach((module) => console.log(`- ${module.bytes} B ${module.id}`));
      });
  },
};

export default defineConfig(({ command }) => ({
  plugins: [bundleCompositionReport],
  experimental: {
    renderBuiltUrl(filename, context) {
      // Image URLs are consumed by the document's Phaser/DOM loaders, not by
      // module resolution. This single-document app lives at root or the Pages
      // directory (no history routes), so document-relative paths avoid repeating
      // the deployment prefix in hundreds of manifests. No <base> override is
      // needed; retain the strict base-uri 'none' security policy.
      // Leave CSS, HTML and JS chunk/preload URLs under Vite's normal handling.
      if (context.hostType === 'js' && context.type === 'asset'
        && /\.(?:webp|png|jpe?g|svg)$/.test(filename)) return filename;
    },
  },
  resolve: command === 'build'
    ? {
      alias: {
        phaser: phaserProductionBuild
      }
    }
    : undefined,
  build: {
    outDir: '.artifacts/build',
    emptyOutDir: true,
    chunkSizeWarningLimit: 1400,
    minify: 'terser',
    terserOptions: {
      ecma: 2020,
      module: true,
      compress: {
        ecma: 2020,
        module: true,
        passes: 5,
        pure_getters: true,
        toplevel: true,
      },
      mangle: {
        toplevel: true,
      },
      format: {
        comments: false,
      },
    },
    rollupOptions: {
      output: {
        manualChunks(id) {
          const moduleId = id.replace(/\\/g, '/');
          if (moduleId.endsWith('/src/main.ts')) return 'index';
          if (moduleId.endsWith('/src/game/battle/enemy-breathing.ts')) return 'enemy-breathing';
          if (moduleId.endsWith('/src/game/run-hud.ts')) return 'run-hud';
          if (moduleId.endsWith('/src/game/route-transition-fx.ts')) return 'route-transition-fx';
          if (moduleId.endsWith('/src/game/battle/state-snapshot.ts')) return 'battle-state-snapshot';
          if (moduleId.endsWith('/src/game/battle/outcome-scene.ts')) return 'battle-outcome-scene';
          if (moduleId.includes('node_modules/phaser')) return 'vendor-phaser';
          // Keep the read-only combat dossier independently measurable. It is
          // a dependency of the lazy hand renderer, never a title preload.
          if (moduleId.endsWith('/src/game/battle/card-detail.ts')) return 'combat-card-detail';
          // Shared by ceremony and offline fallback; no runtime imports or theme ownership.
          if (moduleId.endsWith('/src/game/battle/reward-card-face.ts')) return 'reward-card-face';
          if (moduleId.endsWith('/src/game/battle/encounter-intro.ts')) return 'encounter-intro';
          if (
            moduleId.includes('/src/game/codex-data')
            || moduleId.includes('/data/cards/arcana/')
            || moduleId.includes('/data/game/bird-facts.json')
            || moduleId.includes('/data/game/card-meanings.json')
            || moduleId.includes('/data/game/enemy-variety-contracts.json')
          ) return 'codex-data';
          if (
            moduleId.includes('/src/game/runtime-data')
            || moduleId.includes('/src/game/balance')
            || moduleId.includes('/src/game/difficulty')
            || moduleId.includes('/src/game/enemy-display')
            || moduleId.includes('/data/game/alpha-')
            || moduleId.includes('/data/game/map')
            || moduleId.includes('/data/game/balance-config.json')
            || moduleId.includes('/assets/runtime/cards/card-art-manifest.json')
            || moduleId.includes('/assets/runtime/enemies/enemy-art-manifest.json')
          ) return 'runtime-data';
          if (
            moduleId.includes('/src/game/input-bindings')
            // Already boot-used by rich text; do not let a lazy reader absorb it.
            || moduleId.includes('/src/game/keyword-definitions')
            || moduleId.includes('/src/game/effects/retain')
          ) return 'interaction-rules';
          if (
            moduleId.includes('/src/game/route-gen')
            || moduleId.includes('/src/game/fx')
            || moduleId.includes('/src/game/leaders')
            || moduleId.includes('/src/game/meta')
            || moduleId.includes('/src/game/runtime-images')
            || moduleId.includes('/src/game/scene-runtime')
            || moduleId.includes('/src/game/safe-storage')
            || moduleId.includes('/src/game/deterministic-draw')
            || moduleId.includes('/src/game/effects/')
          ) return 'game-core';
          if (moduleId.includes('node_modules')) return 'vendor';
        }
      }
    }
  },
  server: {
    port: 5173,
    strictPort: false,
    hmr: process.env.BIRD_SQUAD_SMOKE === '1' ? false : undefined,
    watch: {
      ignored: (path) => {
        if (process.env.BIRD_SQUAD_SMOKE === '1') return true;
        const normalized = path.replace(/\\/g, '/');
        return normalized.includes('/.artifacts/')
          || normalized.endsWith('/.artifacts')
          || normalized.includes('/test-results/')
          || normalized.endsWith('/test-results')
          || normalized.includes('/playwright-report/')
          || normalized.endsWith('/playwright-report')
          || normalized.includes('/blob-report/')
          || normalized.endsWith('/blob-report')
          || normalized.includes('/output/')
          || normalized.endsWith('/output')
          || normalized.includes('/.generated/')
          || normalized.endsWith('/.generated');
      },
    },
  },
  preview: {
    port: 4173
  }
}));
